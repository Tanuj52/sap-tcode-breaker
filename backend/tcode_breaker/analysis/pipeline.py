@dataclass
class UserContext:
    """Context the user can add between pipeline stages (from the UI or a pack)."""

    fm_sources: dict[str, str] = field(default_factory=dict)  # FM name -> ABAP source
    fm_hints: dict[str, str] = field(default_factory=dict)  # FM name -> SQL expression template, e.g. "UPPER({INPUT})"
    business_names: dict[str, str] = field(default_factory=dict)  # "MARA" or "MARA-MATNR" -> plain-English name
    table_renames: dict[str, str] = field(default_factory=dict)  # SAP table -> Snowflake object name
    notes: str = ""  # free text passed to the LLM for unresolved steps
    output_table: str | None = None  # force the output internal table


@dataclass
class RunResult:
    name: str
    settings: ProjectSettings
    ingest: IngestResult
    flat: FlatProgram
    parsed: ParsedProgram
    structure: ProgramStructure
    symbols: Symbols
    interp: Interpreter
    output: OutputRec | None
    output_rel: Relation | None
    output_cols: list[OutputColumnSpec]
    sql: SqlResult | None
    issues: list[str] = field(default_factory=list)
    kb: KnowledgeBase | None = None  # the per-run knowledge (catalog + inferred fields)


def run_program(files: dict[str, str], kb: KnowledgeBase, settings: ProjectSettings,
                context: UserContext | None = None, main: str | None = None, mode: str = "select",
                view_name: str | None = None, catalog: dict | None = None) -> RunResult:
    ctx = context or UserContext()
    kb = kb.fork()
    if catalog and catalog.get("tables"):
        kb.apply_catalog(catalog)
        if settings.physical_tables is None:
            settings = settings.model_copy(update={"physical_tables": sorted(catalog["tables"])})
    if ctx.table_renames:
        settings = settings.model_copy(update={"table_renames": {**settings.table_renames, **ctx.table_renames}})
    for name, hint in ctx.fm_hints.items():
        from ..knowledge.models import FMInfo, Provenance

        kb.fms[name.upper()] = FMInfo(name=name.upper(), kind="expression", output="OUTPUT", sql=hint, source=Provenance.CLIENT_PACK,
                                      note="user hint")
    ing = ingest(files, main)
    if not ing.programs:
        raise ValueError("; ".join(i.message for i in ing.issues) or "No program found in the uploaded files")
    flat = ing.programs[0]
    parsed = parse_source(flat.name, flat.text, settings.abap_version)
    for st in parsed.statements:
        st.origin = flat.name
    structure = build_structure(parsed.statements)
    if settings.infer_fields:
        inferred = apply_inference(kb, flat.text)
        if inferred:
            structure.issues.append(f"Field lists inferred from code usage for: {', '.join(sorted(inferred)[:20])}"
                                    + (" ..." if len(inferred) > 20 else ""))
    symbols = Symbols(kb)
    symbols.load(structure)
    fm_sources = {**ing.function_modules, **{k.upper(): v for k, v in ctx.fm_sources.items()}}
    interp = Interpreter(kb, settings, symbols, structure, flat.name, fm_sources)
    interp.run()
    _learn_columns(kb, interp)

    output = _pick_output(interp, ctx.output_table)
    output_rel = output.rel if output else None
    if output is not None and output.var:
        output_rel = output.rel
    cols = _output_columns(interp, output, output_rel)
    if output_rel is None:
        selects = [st for st in parsed.statements if st.type == "Select"]
        if not selects:
            interp.finding("info", "NO_DATA_READ", "The program does not read any database table (no SELECT), so there is "
                           "no data query to convert. It may be a screen, upload, or utility program.", None)
        else:
            interp.finding("warning", "SELECT_NOT_REACHED", f"{len(selects)} SELECT statement(s) exist but are not reached from "
                           "the program's events (called dynamically, from screen modules, or via an unknown entry point). "
                           "Set the output table in the context to convert a specific one.", selects[0])
    sql = None
    if output_rel is not None:
        header = f"Generated by tcode-breaker from {flat.name} ({', '.join(flat.files)})"
        sql = render(output_rel, interp.relations, list(symbols.params.values()), interp.params_used, cols,
                     output.sort if output else [], mode, full_view_name(settings, view_name, flat.name), header)
    return RunResult(flat.name, settings, ing, flat, parsed, structure, symbols, interp, output, output_rel, cols, sql,
                     structure.issues, kb)


def _learn_columns(kb: KnowledgeBase, interp: Interpreter) -> None:
    """Columns the program reads from a table become (inferred) fields of that table in the per-run
    knowledge, unless its field list is authoritative (Snowflake catalog / DDIC export)."""
    from ..knowledge.inference import field_type_index
    from ..knowledge.models import FieldInfo, Provenance, TableInfo

    types = None
    for name, use in interp.tables.items():
        if not use.columns:
            continue
        info = kb.tables.get(name)
        if info is not None and info.fields_complete:
            continue
        missing = [c for c in use.columns if not (info and c in info.fields) and re.fullmatch(r"[A-Z0-9_/]+", c)]
        if not missing:
            continue
        types = types or field_type_index(kb)
        info = info.model_copy(deep=True) if info is not None else TableInfo(name=name, source=Provenance.INFERRED)
        for c in missing:
            ref = types.get(c)
            info.fields[c] = FieldInfo(name=c, ddic_type=ref.ddic_type if ref else None, length=ref.length if ref else None,
                                       decimals=ref.decimals if ref else None, description=ref.description if ref else "",
                                       source=Provenance.INFERRED)
        kb.tables[name] = info


def full_view_name(settings: ProjectSettings, view_name: str | None, program: str) -> str:
    """CREATE VIEW target: <view db>.<view schema>.<name>; an already qualified name is kept."""
    name = (view_name or f"{program}_V").strip()
    if "." in name:
        return name
    db = settings.view_database or settings.target_database
    sc = settings.view_schema or settings.target_schema
    return ".".join(p for p in (db, sc, name) if p)


def _pick_output(interp: Interpreter, forced: str | None) -> OutputRec | None:
    if forced:
        for o in interp.outputs:
            if o.var == forced.upper():
                return o
        st = interp.itabs.get(forced.upper())
        if st is not None and st.rel is not None:
            return OutputRec("forced", forced.upper(), st.rel, st.sort, None, None)  # type: ignore[arg-type]
    if interp.outputs:
        return interp.outputs[-1]
    listed = _write_list_output(interp)
    if listed is not None:
        return listed
    # fallback: the last relation of the last written table
    candidates = [r for r in interp.relations if not r.is_empty and not r.var.startswith("SELECT_LOOP")]
    if not candidates:
        return None
    rel = candidates[-1]
    st = interp.itabs.get(rel.var)
    interp.finding("warning", "NO_OUTPUT_CALL", f"No ALV/SALV output call found; using {rel.var} as the result.", None)
    return OutputRec("inferred", rel.var, st.rel if st and st.rel else rel, st.sort if st else [], None, None)  # type: ignore[arg-type]


def _write_list_output(interp: Interpreter) -> OutputRec | None:
    """Classic list report: `LOOP AT itab INTO wa. WRITE: / wa-f1, wa-f2. ENDLOOP.` -> itab, columns f1, f2."""
    import re

    from .blocks import Control
    from .expr import lit

    best = None
    for r in interp.structure.routines.values():
        stack = list(r.items)
        while stack:
            it = stack.pop(0)
            if not isinstance(it, Control):
                continue
            for b in it.branches:
                stack.extend(b.items)
            if it.type != "Loop":
                continue
            m = re.match(r"\s*LOOP\s+AT\s+([A-Za-z0-9_]+)(?:\[\])?\s+(?:INTO|ASSIGNING)\s+(?:DATA\(|FIELD-SYMBOL\()?(<?[A-Za-z0-9_]+>?)",
                         it.header.text, re.IGNORECASE)
            if not m:
                continue
            itab, wa = m.group(1).upper(), m.group(2).upper()
            fields: list[str] = []
            for st in _flat_stmts(it):
                if st.type == "Write":
                    for f in re.findall(rf"(?<![A-Za-z0-9_]){re.escape(wa)}-([A-Za-z0-9_]+)", st.text, re.IGNORECASE):
                        if f.upper() not in fields:
                            fields.append(f.upper())
            if fields and (best is None or (it.header.row or 0) > best[0]):
                best = (it.header.row or 0, itab, fields, it.header)
    if best is None:
        return None
    _, itab, fields, stmt = best
    st = interp.itabs.get(itab)
    if st is None or st.rel is None:
        return None
    rows = [{"FIELDNAME": lit(f"'{f}'")} for f in fields if st.rel.col(f) is not None]
    interp.finding("info", "WRITE_LIST_OUTPUT", f"List output (WRITE) of {itab}: columns {', '.join(fields[:12])}.", stmt)
    return OutputRec("write_list", itab, st.rel, st.sort, rows or None, stmt)  # type: ignore[arg-type]


def _flat_stmts(ctl):
    from .blocks import flatten

    return flatten([ctl])


def _output_columns(interp: Interpreter, output: OutputRec | None, rel: Relation | None) -> list[OutputColumnSpec]:
    if rel is None:
        return []
    rows = output.fieldcat if output else None
    if rows and not any("__MERGE__" in r for r in rows):
        cols = []
        for r in rows:
            fname = (r.get("FIELDNAME").sql if r.get("FIELDNAME") else "").strip("'").upper()
            if not fname:
                continue
            hidden = any((r.get(f).sql if r.get(f) else "''").strip("'").upper() == "X" for f in ("NO_OUT", "TECH"))
            label = next(((r.get(f).sql or "").strip("'") for f in ("SELTEXT_M", "SELTEXT_L", "SCRTEXT_M", "COLTEXT", "REPTEXT_DDIC", "SELTEXT_S") if r.get(f)), "")
            if rel.col(fname) is None:
                interp.finding("warning", "FIELDCAT_UNKNOWN", f"Field catalog column {fname} is not in the output table.", output.stmt)
                continue
            cols.append(OutputColumnSpec(fname, label, hidden))
        if cols:
            return cols
    return [OutputColumnSpec(c) for c in rel.column_names]
